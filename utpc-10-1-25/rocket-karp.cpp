int find(int l, int r) {
    while (l < r) {
        int m = (l+r)/2;
        char c = ask(m);
        if (c == '=') {
            return m;
        } else if (c == '<') {
            r = m-1;
        } else {
            l = m+1;
        }
    }
    return l;
}

