ll gcd(ll a, ll b) {
    return b ? gcd(b, a % b) : a;
}

ll mul(ll a, ll b, ll p) {
    return (a * b) % p;
}

ll inv(ll a, ll p) {
    ll x = 1, y = 0, m = p;
    while (a > 1) {
        ll q = a / m;
        ll t = m;
        m = a % m;
        a = t;
        t = y;
        y = x - q * y;
        x = t;
    }
    if (x < 0) x += p;
    return x;
}

ll solve(ll n, ll x, ll y, ll fx, ll fy) {
    ll ans = 0;
    ans += abs(fx-x)/n;
    ans += abs(fy-y)/n;
    ll u = x+y, fu = fx+fy;
    ll v = y-x, fv = fy-fx;
    if ((fu%(2*n)+2*n)%(2*n) == 0) {
        if (fu > u) fu += n;
        else fu -= n;
    }
    if ((fv%(2*n)+2*n)%(2*n) == 0) {
        if (fv > v) fv += n;
        else fv -= n;
    }
    ans += abs(fu-u)/(2*n);
    ans += abs(fv-v)/(2*n);
    return ans;
}

