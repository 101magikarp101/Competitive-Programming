ll T, S;

ll spid(ll x, ll y) {
    if (y <= x) return 2*x + y;
    return 3*x + 2*(y-x);
}

ll find(ll x) {
    ll l = 0, r = 1e6;
    while (l < r) {
        ll m = (l+r+1)/2;
        if (spid(x, m) <= 2*S) l = m;
        else r = m-1;
    }
    return l;
}

ll gcd(ll a, ll b) {
    return b ? gcd(b, a%b) : a;
}

